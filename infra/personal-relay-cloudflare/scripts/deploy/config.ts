export class DeployConfigError extends Error {
  override name = "DeployConfigError";
}

/** Strips JSONC comments without touching strings, so the template can be commented. */
export function stripJsonComments(text: string): string {
  let output = "";
  let inString = false;
  let escaped = false;
  let index = 0;

  while (index < text.length) {
    const character = text[index] ?? "";
    const next = text[index + 1] ?? "";

    if (inString) {
      output += character;
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === '"') inString = false;
      index += 1;
      continue;
    }
    if (character === '"') {
      inString = true;
      output += character;
      index += 1;
      continue;
    }
    if (character === "/" && next === "/") {
      while (index < text.length && text[index] !== "\n") index += 1;
      continue;
    }
    if (character === "/" && next === "*") {
      index += 2;
      while (index < text.length && !(text[index] === "*" && text[index + 1] === "/")) index += 1;
      index += 2;
      continue;
    }
    output += character;
    index += 1;
  }
  return output;
}

export function parseJsonc(text: string, source: string): Record<string, unknown> {
  let parsed: unknown;
  try {
    parsed = JSON.parse(stripJsonComments(text));
  } catch (cause) {
    throw new DeployConfigError(`${source} is not valid JSONC: ${(cause as Error).message}`);
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
    throw new DeployConfigError(`${source} must contain a JSON object.`);
  }
  return parsed as Record<string, unknown>;
}

export interface DeployConfigInput {
  readonly template: Record<string, unknown>;
  readonly workerName: string;
  readonly main: string;
  readonly portalDirectory: string;
  readonly vars: Readonly<Record<string, string>>;
  readonly relayDomain: string | null;
}

export function buildDeployConfig(input: DeployConfigInput): Record<string, unknown> {
  const template = structuredClone(input.template);
  const assets = (template.assets ?? {}) as Record<string, unknown>;
  const templateVars = (template.vars ?? {}) as Record<string, unknown>;

  const config: Record<string, unknown> = {
    ...template,
    name: input.workerName,
    main: input.main,
    assets: { ...assets, directory: input.portalDirectory },
    vars: { ...templateVars, ...input.vars },
  };
  delete config.$schema;

  if (input.relayDomain === null) {
    delete config.routes;
    delete config.route;
    config.workers_dev = true;
  } else {
    config.workers_dev = false;
    config.routes = [{ pattern: input.relayDomain, custom_domain: true }];
  }
  return config;
}

export function serializeDeployConfig(config: Record<string, unknown>): string {
  return `// Generated by the T3 Code Cloudflare relay deploy. Rerun the deploy to regenerate.\n${JSON.stringify(
    config,
    null,
    2,
  )}\n`;
}
